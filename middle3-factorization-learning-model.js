  function normalizedText(value) {
    return String(value ?? "")
      .normalize("NFKC")
      .replace(/[−–—]/g, "-")
      .replace(/[×·]/g, "*")
      .replace(/÷/g, "/")
      .replace(/²/g, "^2")
      .replace(/\s+/g, "")
      .toLowerCase();
  }

